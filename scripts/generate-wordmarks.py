#!/usr/bin/env python3
"""generate-wordmarks.py - cut the marks of the panel into outlines.

The name plate prints the mark of the machine. It is set in Futura W02
Light, a commercial face of Linotype, so the panel does not ship the
face: the mark is cut here into an SVG outline and the panel draws the
outline. The face carries fsType 0 in its OS/2 table, installable
embedding, so a document that carries the outline may be distributed.

The outline is drawn on the line box of the face, one em high, and the
box of the outline is the box of its ink, so the mark fills the plate
without the empty line of a text that is not there.

Usage:
    python3 scripts/generate-wordmarks.py [path/to/FuturaW02-Light.woff2]

Needs fontTools, uharfbuzz and brotli (the face ships as a WOFF2). It is
not part of the build: the file it writes is committed.

    uv run --with fonttools --with uharfbuzz --with brotli \
        python3 scripts/generate-wordmarks.py
"""

import sys
import tempfile
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = Path(
    sys.argv[1] if len(sys.argv) > 1 else ROOT / "vendor/fonts/FuturaW02-Light.woff2"
)
OUT = ROOT / "src/ui/wordmark-paths.ts"

# The marks the panel prints, and the tracking of each in em. The mark of
# the machine is tracked out like the logo of the original unit.
WORDS = {
    "POPPY 7": 0.08,
}


def cut(font, path, word, tracking):
    """The outline of a word, in the em of the face, and its ink box."""
    upem = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    descent = -font["hhea"].descent

    # The line box is one em, and the browser puts the baseline where the
    # half-leading leaves it.
    baseline = ascent + (upem - (ascent + descent)) / 2

    face = hb.Face(hb.Blob.from_file_path(str(path)))
    shaped = hb.Font(face)
    shaped.scale = (upem, upem)
    buffer = hb.Buffer()
    buffer.add_str(word)
    buffer.guess_segment_properties()
    hb.shape(shaped, buffer)

    order = font.getGlyphOrder()
    glyphs = font.getGlyphSet()
    recorded = RecordingPen()

    x = 0.0
    count = len(buffer.glyph_infos)
    for index, (info, position) in enumerate(
        zip(buffer.glyph_infos, buffer.glyph_positions)
    ):
        name = order[info.codepoint]
        if name in glyphs:
            # The face is drawn with the y axis up and the panel with the
            # y axis down: the word is turned over, and the baseline of
            # the line box comes with it.
            turned = TransformPen(recorded, (1, 0, 0, -1, 0, baseline))
            placed = TransformPen(turned, (1, 0, 0, 1, x + position.x_offset, 0))
            glyphs[name].draw(placed)
        x += position.x_advance
        if index < count - 1:
            x += tracking * upem

    outline = SVGPathPen(glyphs)
    recorded.replay(outline)

    # The mark stands on the plate without the empty line box around it:
    # the box of the outline is the box of the ink.
    ink = BoundsPen(glyphs)
    recorded.replay(ink)

    return outline.getCommands(), ink.bounds, upem


def main():
    if not FONT.exists():
        raise SystemExit(f"the face is not there: {FONT}")

    font = TTFont(FONT)
    upem = font["head"].unitsPerEm

    lines = [
        "/*",
        " * The marks the panel prints, cut into outlines.",
        " *",
        " * Generated by scripts/generate-wordmarks.py - do not edit by hand.",
        " * The face is Futura W02 Light; the panel ships the outlines and",
        " * not the face. The box of an outline is the box of its ink, in",
        " * the em of the face, so the mark fills the plate it stands on.",
        " */",
        "",
        "export interface Wordmark {",
        "  /** The box of the ink, in the em of the face. */",
        "  readonly viewBox: string;",
        "  /** The outline of the word. */",
        "  readonly path: string;",
        "}",
        "",
        "export const WORDMARKS: Readonly<Record<string, Wordmark>> = {",
    ]

    with tempfile.TemporaryDirectory() as scratch:
        # HarfBuzz reads the tables of a plain font, and the face ships as
        # a WOFF2: it is turned back into one for the shaping.
        plain = Path(scratch) / "face.ttf"
        font.flavor = None
        font.save(plain)

        for word, tracking in WORDS.items():
            path, ink, upem = cut(font, plain, word, tracking)
            if ink is None:
                raise SystemExit(f"the word has no ink: {word}")
            xmin, ymin, xmax, ymax = ink
            box = f"{xmin:.0f} {ymin:.0f} {xmax - xmin:.0f} {ymax - ymin:.0f}"
            lines.append(f'  "{word}": {{')
            lines.append(f'    viewBox: "{box}",')
            lines.append(f'    path: "{path}",')
            lines.append("  },")

    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(WORDS)} words)")


if __name__ == "__main__":
    main()
