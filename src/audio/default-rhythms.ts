/*
 * default-rhythms.ts - the rhythms the user patterns come up with.
 *
 * The twenty slots of the user banks come up with the rhythms of the two
 * banks: the ten of bank A and the ten of bank B. They are the rhythms
 * the machine was given, and the user writes over them: a slot that was
 * written keeps what was written in it, and a slot that was not written
 * goes back to the rhythm it came up with.
 *
 * The rhythms belong to the panel, not to the engine: the engine holds the
 * twenty slots and the pattern that is written in them, and it hands the
 * pattern back exactly as it was stored.
 *
 * A column holds the fifteen instruments in its lower bits and the accent
 * flag in its sixteenth one. The instrument order is the engine's own: the
 * bass drum is the first voice and the quijada the last.
 */

